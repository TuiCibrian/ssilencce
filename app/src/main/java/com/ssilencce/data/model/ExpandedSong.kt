package com.ssilencce.data.model

import kotlinx.parcelize.Parcelize

@Parcelize
class ExpandedSong(
    override val id: Long,
    override val data: String,
    override val title: String,
    override val trackNumber: Int,
    override val year: Int,
    override val size: Long,
    override val duration: Long,
    override val dateAdded: Long,
    override val rawDateModified: Long,
    override val albumId: Long,
    override val albumName: String,
    override val artistId: Long,
    override val artistName: String,
    override val albumArtistName: String?,
    override val genreName: String?,
    override val composerName: String? = null,
    override val discNumber: Int = 0,
    val playCount: Int,
    val skipCount: Int,
    val lastPlayedAt: Long,
    val isFavorite: Boolean,
    override val volumeName: String? = null,
) : Song(
        id = id,
        data = data,
        title = title,
        trackNumber = trackNumber,
        year = year,
        size = size,
        duration = duration,
        dateAdded = dateAdded,
        rawDateModified = rawDateModified,
        albumId = albumId,
        albumName = albumName,
        artistId = artistId,
        artistName = artistName,
        albumArtistName = albumArtistName,
        genreName = genreName,
        volumeName = volumeName,
        composerName = composerName,
        discNumber = discNumber,
    ) {
    constructor(
        song: Song,
        playCount: Int,
        skipCount: Int,
        lastPlayedAt: Long,
        isFavorite: Boolean,
    ) : this(
        id = song.id,
        data = song.data,
        title = song.title,
        trackNumber = song.trackNumber,
        year = song.year,
        size = song.size,
        duration = song.duration,
        dateAdded = song.dateAdded,
        rawDateModified = song.rawDateModified,
        albumId = song.albumId,
        albumName = song.albumName,
        artistId = song.artistId,
        artistName = song.artistName,
        albumArtistName = song.albumArtistName,
        genreName = song.genreName,
        volumeName = song.volumeName,
        composerName = song.composerName,
        discNumber = song.discNumber,
        playCount = playCount,
        skipCount = skipCount,
        lastPlayedAt = lastPlayedAt,
        isFavorite = isFavorite,
    )
}
