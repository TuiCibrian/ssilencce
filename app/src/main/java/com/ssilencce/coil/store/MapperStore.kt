package com.ssilencce.coil.store

import android.content.SharedPreferences
import coil3.map.Mapper
import coil3.request.Options
import com.ssilencce.coil.model.ArtistImage
import com.ssilencce.coil.model.AudioCover
import com.ssilencce.coil.model.AutoGeneratedImage
import com.ssilencce.coil.model.PlaylistImage
import com.ssilencce.core.model.filesystem.FileSystemItem
import com.ssilencce.data.local.room.PlaylistWithSongs
import com.ssilencce.data.mapper.toSongs
import com.ssilencce.data.model.*
import com.ssilencce.extensions.media.albumArtistName
import com.ssilencce.util.IGNORE_MEDIA_STORE
import com.ssilencce.util.USE_FOLDER_ART

class SongMapper(
    private val preferences: SharedPreferences,
) : Mapper<Song, AudioCover> {
    override fun map(
        data: Song,
        options: Options,
    ): AudioCover? =
        AudioCover(
            albumId = data.albumId,
            uri = data.uri,
            path = data.data,
            artistName = data.albumArtistName(),
            albumName = data.albumName,
            title = data.title,
            lastModified = data.rawDateModified,
            isAlbum = false,
            isIgnoreMediaStore = preferences.getBoolean(IGNORE_MEDIA_STORE, true),
            isUseFolderArt = preferences.getBoolean(USE_FOLDER_ART, false),
        )
}

class AlbumMapper(
    private val preferences: SharedPreferences,
) : Mapper<Album, AudioCover> {
    override fun map(
        data: Album,
        options: Options,
    ): AudioCover? =
        data.safeGetFirstSong().let {
            AudioCover(
                albumId = data.id,
                uri = it.uri,
                path = it.data,
                artistName = it.albumArtistName(),
                albumName = it.albumName,
                title = it.title,
                lastModified = it.rawDateModified,
                isAlbum = true,
                isIgnoreMediaStore = preferences.getBoolean(IGNORE_MEDIA_STORE, true),
                isUseFolderArt = preferences.getBoolean(USE_FOLDER_ART, false),
            )
        }
}

class ArtistMapper : Mapper<Artist, ArtistImage> {
    override fun map(
        data: Artist,
        options: Options,
    ): ArtistImage? =
        ArtistImage(
            id = data.id,
            coverUri = data.safeGetFirstAlbum().albumCover,
            name = data.name,
        )
}

class PlaylistMapper : Mapper<PlaylistWithSongs, PlaylistImage> {
    override fun map(
        data: PlaylistWithSongs,
        options: Options,
    ): PlaylistImage? = PlaylistImage(data.playlistEntity, data.songs.toSongs())
}

class GenreMapper : Mapper<Genre, AutoGeneratedImage> {
    override fun map(
        data: Genre,
        options: Options,
    ): AutoGeneratedImage? = AutoGeneratedImage(AutoGeneratedImage.TYPE_GENRE, data.id, data.songCount)
}

class YearMapper : Mapper<ReleaseYear, AutoGeneratedImage> {
    override fun map(
        data: ReleaseYear,
        options: Options,
    ): AutoGeneratedImage? = AutoGeneratedImage(AutoGeneratedImage.TYPE_YEAR, data.year.toLong(), data.songCount)
}

class FileMapper(
    private val preferences: SharedPreferences,
) : Mapper<FileSystemItem, AudioCover> {
    override fun map(
        data: FileSystemItem,
        options: Options,
    ): AudioCover? {
        val song = data as? Song
        if (song != null) {
            return AudioCover(
                albumId = data.albumId,
                uri = data.uri,
                path = data.data,
                artistName = data.albumArtistName(),
                albumName = data.albumName,
                title = data.title,
                lastModified = data.rawDateModified,
                isAlbum = false,
                isIgnoreMediaStore = preferences.getBoolean(IGNORE_MEDIA_STORE, true),
                isUseFolderArt = preferences.getBoolean(USE_FOLDER_ART, false),
            )
        }
        return null
    }
}
