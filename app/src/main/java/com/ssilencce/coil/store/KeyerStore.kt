package com.ssilencce.coil.store

import android.content.SharedPreferences
import coil3.key.Keyer
import coil3.request.Options
import com.ssilencce.coil.CustomArtistImageManager
import com.ssilencce.coil.model.ArtistImage
import com.ssilencce.coil.model.AudioCover
import com.ssilencce.coil.model.AutoGeneratedImage
import com.ssilencce.coil.model.PlaylistImage
import com.ssilencce.util.DISABLE_ALBUM_ART

class AudioCoverKeyer(
    private val preferences: SharedPreferences,
) : Keyer<AudioCover> {
    override fun key(
        data: AudioCover,
        options: Options,
    ): String? =
        buildString {
            if (data.isAlbum) {
                append("album::")
            } else {
                append("song::")
            }
            append("albumId=").append(data.albumId)
            append("|uri=").append(data.uri.toString())
            append("|path=").append(data.path)
            append("|folderArt=").append(data.isUseFolderArt)
            append("|lastModified=").append(data.lastModified)
            append("|artDisabled=").append(preferences.getBoolean(DISABLE_ALBUM_ART, false))
        }
}

class ArtistImageKeyer(
    private val customArtistImageManager: CustomArtistImageManager,
    private val preferences: SharedPreferences,
) : Keyer<ArtistImage> {
    override fun key(
        data: ArtistImage,
        options: Options,
    ): String? {
        val hasCustomImage = customArtistImageManager.hasCustomImage(data)
        val signature = customArtistImageManager.getSignature(data)
        return "artist::id=${data.id}|name=${data.name}|coverUri=${data.coverUri}|hasCustomImage=$hasCustomImage|signature=$signature" +
            "|artDisabled=${preferences.getBoolean(DISABLE_ALBUM_ART, false)}"
    }
}

class PlaylistImageKeyer(
    private val preferences: SharedPreferences,
) : Keyer<PlaylistImage> {
    override fun key(
        data: PlaylistImage,
        options: Options,
    ): String? =
        "playlist::id=${data.playlistEntity.playListId}" +
            "|customCoverUri=${data.playlistEntity.customCoverUri}" +
            "|songs=${data.songs.size}" +
            "|artDisabled=${preferences.getBoolean(DISABLE_ALBUM_ART, false)}"
}

class AutoGeneratedImageKeyer(
    private val preferences: SharedPreferences,
) : Keyer<AutoGeneratedImage> {
    override fun key(
        data: AutoGeneratedImage,
        options: Options,
    ): String? =
        "auto-generated::type=${data.type}|id=${data.id}|songCount=${data.songCount}" +
            "|artDisabled=${preferences.getBoolean(DISABLE_ALBUM_ART, false)}"
}
