package com.ssilencce.coil.fetcher

import android.content.Context
import android.content.SharedPreferences
import coil3.ImageLoader
import coil3.decode.DataSource
import coil3.fetch.FetchResult
import coil3.fetch.Fetcher
import coil3.fetch.ImageFetchResult
import coil3.request.Options
import com.ssilencce.coil.model.AutoGeneratedImage
import com.ssilencce.coil.util.AutoGeneratedImageUtil
import com.ssilencce.data.local.repository.Repository
import com.ssilencce.util.DISABLE_ALBUM_ART

class AutoGeneratedImageFetcher(
    private val context: Context,
    private val repository: Repository,
    private val image: AutoGeneratedImage,
    private val artworkEnabled: Boolean,
) : Fetcher {
    override suspend fun fetch(): FetchResult? {
        if (!artworkEnabled) return null
        if (image.id == -1L) return null

        val songs =
            when (image.type) {
                AutoGeneratedImage.TYPE_GENRE -> repository.songsByGenre(image.id)
                AutoGeneratedImage.TYPE_YEAR -> repository.songsByYear(image.id.toInt())
                else -> emptyList()
            }
        val image =
            AutoGeneratedImageUtil.getImage(context, songs)
                ?: return null

        return ImageFetchResult(
            image = image,
            isSampled = false,
            dataSource = DataSource.DISK,
        )
    }

    class Factory(
        private val preferences: SharedPreferences,
        private val repository: Repository,
    ) : Fetcher.Factory<AutoGeneratedImage> {
        override fun create(
            data: AutoGeneratedImage,
            options: Options,
            imageLoader: ImageLoader,
        ): Fetcher? =
            AutoGeneratedImageFetcher(
                context = options.context,
                repository = repository,
                image = data,
                artworkEnabled = !preferences.getBoolean(DISABLE_ALBUM_ART, false),
            )
    }
}
