package com.ssilencce.coil.fetcher

import android.content.Context
import android.content.SharedPreferences
import coil3.ImageLoader
import coil3.SingletonImageLoader
import coil3.decode.DataSource
import coil3.fetch.FetchResult
import coil3.fetch.Fetcher
import coil3.fetch.ImageFetchResult
import coil3.request.ImageRequest
import coil3.request.Options
import coil3.size.Size
import com.ssilencce.coil.model.PlaylistImage
import com.ssilencce.coil.util.AutoGeneratedImageUtil
import com.ssilencce.data.local.room.PlaylistEntity
import com.ssilencce.util.DISABLE_ALBUM_ART

class PlaylistImageFetcher(
    private val context: Context,
    private val size: Size,
    private val image: PlaylistImage,
    private val artworkEnabled: Boolean,
) : Fetcher {
    private val playlistEntity = image.playlistEntity

    override suspend fun fetch(): FetchResult? {
        if (!artworkEnabled) return null
        if (image.playlistEntity == PlaylistEntity.Empty) return null

        val customCoverUri = playlistEntity.customCoverUri
        val image =
            if (!customCoverUri.isNullOrEmpty()) {
                val result =
                    SingletonImageLoader
                        .get(context)
                        .execute(
                            ImageRequest
                                .Builder(context)
                                .data(customCoverUri)
                                .size(size)
                                .build(),
                        )

                // If custom cover fails to load, fall back to auto-generated
                result.image ?: AutoGeneratedImageUtil.getImage(context, image.songs)
            } else {
                // No custom cover, use auto-generated
                AutoGeneratedImageUtil.getImage(context, image.songs)
            } ?: return null

        return ImageFetchResult(
            image = image,
            isSampled = false,
            dataSource = DataSource.DISK,
        )
    }

    class Factory(
        private val preferences: SharedPreferences,
    ) : Fetcher.Factory<PlaylistImage> {
        override fun create(
            data: PlaylistImage,
            options: Options,
            imageLoader: ImageLoader,
        ): Fetcher? =
            PlaylistImageFetcher(
                context = options.context,
                size = options.size,
                image = data,
                artworkEnabled = !preferences.getBoolean(DISABLE_ALBUM_ART, false),
            )
    }
}
