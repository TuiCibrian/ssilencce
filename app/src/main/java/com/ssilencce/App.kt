class App :
    Application(),
    SingletonImageLoader.Factory {
    override fun onCreate() {
        super.onCreate()
        startKoin {
            androidContext(this@App)
            modules(appModules)
        }
        ExtraFormatScanner.scheduleIfNeeded()

        if (BuildConfig.DEBUG) enableStrictMode()

        AppVisibility.register(this)

        val prefs = PreferenceManager.getDefaultSharedPreferences(this)
        if (!prefs.contains(AURORA_APPEARANCE)) {
            val isNewInstallation = prefs.all.isEmpty()
            prefs.edit {
                putBoolean(AURORA_APPEARANCE, isNewInstallation)
                if (isNewInstallation) {
                    putBoolean(USE_CUSTOM_FONT, false)
                    // The wizard is only offered automatically on a new installation. The
                    // preference defaults to true so an existing installation never sees it.
                    putBoolean(SETUP_WIZARD_COMPLETED, false)
                }
            }
        }
        // we cannot call setDefaultValues for multiple fragment based XML preference
        // files with readAgain flag set to false, so always check KEY_HAS_SET_DEFAULT_VALUES
        if (!prefs.getBoolean(PreferenceManager.KEY_HAS_SET_DEFAULT_VALUES, false)) {
            for (screen in SettingsScreen.entries) {
                PreferenceManager.setDefaultValues(this, screen.layoutRes, true)
            }
            if (isExperimentalBuild()) {
                prefs.edit { putBoolean(EXPERIMENTAL_UPDATES, true) }
            }
        }
        Preferences.migrateLegacyPlaybackPreferences()

        // Process-scoped delivery keeps the rescan off the battery unless a volume really mounts.
        ContextCompat.registerReceiver(
            this,
            MediaMountRescanReceiver(),
            IntentFilter(Intent.ACTION_MEDIA_MOUNTED),
            ContextCompat.RECEIVER_NOT_EXPORTED,
        )

        // setting Error activity
        CaocConfig.Builder
            .create()
            .errorActivity(ErrorActivity::class.java)
            .restartActivity(MainActivity::class.java)
            .apply()

        AppCompatDelegate.setDefaultNightMode(getDayNightMode())
    }

    override fun newImageLoader(context: PlatformContext): ImageLoader {
        return ImageLoader
            .Builder(context)
            .crossfade(true)
            .allowHardware(false)
            .components {
                // Song/album
                add(SongMapper(preferences = get()))
                add(FileMapper(preferences = get()))
                add(AlbumMapper(preferences = get()))
                add(AudioCoverKeyer(preferences = get()))
                add(
                    AudioCoverFetcher.Factory(
                        preferences = get(),
                        repository = get(),
                    ),
                )

                // Artist
                add(ArtistMapper())
                add(ArtistImageKeyer(customArtistImageManager = get(), preferences = get()))
                add(
                    ArtistImageFetcher.Factory(
                        preferences = get(),
                        customImageManager = get(),
                        repository = get(),
                    ),
                )

                // Playlist
                add(PlaylistMapper())
                add(PlaylistImageKeyer(preferences = get()))
                add(PlaylistImageFetcher.Factory(preferences = get()))

                // Auto-generated image
                add(GenreMapper())
                add(YearMapper())
                add(AutoGeneratedImageKeyer(preferences = get()))
                add(AutoGeneratedImageFetcher.Factory(preferences = get(), repository = get()))

                // Network
                add(KtorNetworkFetcherFactory())
            }.also { builder ->
                if (BuildConfig.DEBUG) {
                    builder.logger(
                        object : Logger {
                            override var minLevel = Logger.Level.Verbose

                            override fun log(
                                tag: String,
                                level: Logger.Level,
                                message: String?,
                                throwable: Throwable?,
                            ) {
                                if (level < minLevel) return
                                message?.let { msg -> Log.println(level.ordinal + 2, tag, msg) }
                                throwable?.let { thr ->
                                    Log.println(level.ordinal + 2, tag, Log.getStackTraceString(thr))
                                }
                            }
                        },
                    )
                }
            }.build()
    }

    override fun onTrimMemory(level: Int) {
        super.onTrimMemory(level)
        ReplayGainTagExtractor.clearCache()

        val imageLoader = SingletonImageLoader.get(this)
        imageLoader.memoryCache?.clear()
    }

    private fun enableStrictMode() {
        StrictMode.setVmPolicy(
            VmPolicy
                .Builder()
                .detectAll()
                .penaltyLog()
                .build(),
        )

        StrictMode.setThreadPolicy(
            ThreadPolicy
                .Builder()
                .detectAll()
                .penaltyLog()
                .penaltyFlashScreen()
                .build(),
        )
    }

    companion object {
        fun isFDroidBuild() = BuildConfig.FLAVOR.equals("fdroid", ignoreCase = true)

        fun isPlayStoreBuild() = BuildConfig.FLAVOR.equals("playstore", ignoreCase = true)

        fun isExperimentalBuild(): Boolean = BuildConfig.VERSION_NAME.contains("(alpha|beta|rc)".toRegex(RegexOption.IGNORE_CASE))
    }
}
